"""Gold answers: run every question's reference SQL against the pinned serving file.

`python -m bharat.eval gold` writes `eval/gold.json` (the values the scorer compares with,
tied to the serving file by its SHA-256) and `eval/REVIEW.md` (the same, readable, for the
author to check by hand against the source files).
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import duckdb

from bharat.agent.sql_guard import check_sql
from bharat.eval.questions import ALLOWED_TABLES, EVAL_DIR, Question, load_questions
from bharat.ingest.common import sha256_file

SERVING_DB = EVAL_DIR.parent / "data" / "serving" / "serving.duckdb"


class GoldError(ValueError):
    pass


def run_gold(con: duckdb.DuckDBPyConnection, question: Question) -> list[list]:
    """The reference SQL's rows, after the same guard the agent's SQL must pass."""
    guard = check_sql(question.gold_sql, ALLOWED_TABLES)
    if not guard.ok:
        raise GoldError(f"{question.id}: gold SQL fails the guard: {guard.errors}")
    rows = [list(row) for row in con.execute(guard.sql).fetchall()]
    shape_problem = _shape_problem(question, rows)
    if shape_problem:
        raise GoldError(f"{question.id}: {shape_problem}; got {rows[:5]}")
    return rows


def _is_number(value) -> bool:
    return isinstance(value, int | float) and not isinstance(value, bool) and math.isfinite(value)


def _shape_problem(question: Question, rows: list[list]) -> str | None:
    if not rows:
        return "no rows"
    if question.kind == "number":
        if len(rows) != 1 or not _is_number(rows[0][0]):
            return "expected one number"
    elif question.kind in ("ranking", "series"):
        if any(len(r) < 2 or not isinstance(r[0], str) or not _is_number(r[1]) for r in rows):
            return "expected rows of (label, number)"
        if question.kind == "series" and len(rows) < 2:
            return "a series needs at least two points"
    elif question.kind == "correlation":
        r, n = rows[0][0], rows[0][1]
        if len(rows) != 1 or not _is_number(r) or not -1 <= r <= 1 or not n or n < 5:
            return "expected one row of (r between -1 and 1, n of at least 5)"
    return None


def indian(value: float, decimals: int = 2) -> str:
    """12345678.9 -> '1,23,45,678.90' (lakh and crore grouping)."""
    sign = "-" if value < 0 else ""
    whole, _, frac = f"{abs(value):.{decimals}f}".partition(".")
    head, tail = whole[:-3], whole[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    text = ",".join([*groups, tail]) if groups else tail
    return sign + text + (f".{frac}" if frac else "")


def _show(question: Question, rows: list[list]) -> str:
    unit = f" {question.unit}" if question.unit else ""
    if question.kind == "number":
        return indian(rows[0][0]) + unit
    if question.kind == "correlation":
        return f"r = {rows[0][0]:.3f} (n = {rows[0][1]})"
    return "<br>".join(f"{label}: {indian(value)}{unit}" for label, value, *_ in rows)


def build_gold(database: Path = SERVING_DB) -> dict:
    con = duckdb.connect(str(database), read_only=True)
    try:
        built = con.execute("select built_at, git_sha from build_info").fetchall()[0]
        gold: dict = {
            "serving_sha256": sha256_file(database),
            "built_at": str(built[0]),
            "built_from_commit": built[1],
            "questions": {},
        }
        for split in ("dev", "test"):
            for q in load_questions(split):
                entry: dict = {"split": split, "expected": q.expected, "kind": q.kind}
                if q.gold_sql:
                    entry["rows"] = run_gold(con, q)
                gold["questions"][q.id] = entry
    finally:
        con.close()
    return gold


def review_markdown(gold: dict) -> str:
    lines = [
        "# Benchmark review",
        "",
        "Generated by `python -m bharat.eval gold`. Do not edit by hand.",
        "",
        f"- Serving file SHA-256: `{gold['serving_sha256']}`",
        f"- Built at {gold['built_at']} from commit `{gold['built_from_commit']}`",
        "",
        "Check at least 20% of the answers against the source files and tick them in",
        "`eval/hand_checks.md`.",
    ]
    for split in ("dev", "test"):
        lines += ["", f"## {split} ({len(load_questions(split))} questions)", ""]
        lines += [
            "| id | type | question | expected | gold answer | caveats |",
            "|---|---|---|---|---|---|",
        ]
        for q in load_questions(split):
            entry = gold["questions"][q.id]
            answer = _show(q, entry["rows"]) if "rows" in entry else (q.reason or "")
            text = " ".join(q.question.split()).replace("|", "\\|")
            lines.append(
                f"| {q.id} | {q.type} | {text} | {q.expected} | {answer} | {', '.join(q.caveats)} |"
            )
    return "\n".join(lines) + "\n"


def write_gold(database: Path = SERVING_DB, out_dir: Path = EVAL_DIR) -> tuple[Path, Path]:
    gold = build_gold(database)
    gold_path = out_dir / "gold.json"
    gold_path.write_text(json.dumps(gold, indent=1, default=str) + "\n", encoding="utf-8")
    review_path = out_dir / "REVIEW.md"
    review_path.write_text(review_markdown(gold), encoding="utf-8")
    return gold_path, review_path
